#!/bin/bash

# Nefarious IRCd Docker Entrypoint
# Reads base.conf-dist, replaces every %VARIABLE% placeholder with the value
# of the environment variable of that name, and writes out base.conf.  If
# that cannot be done completely the script exits non-zero and the ircd is
# not started.

BASECONFDIST=/home/nefarious/ircd/base.conf-dist
BASECONF=/home/nefarious/ircd/base.conf
IRCDPEM=/home/nefarious/ircd/ircd.pem

# Set defaults for required variables (can be overridden by environment)
: "${IRCD_GENERAL_NAME:=localhost.localdomain}"
: "${IRCD_GENERAL_DESCRIPTION:=localhost.localdomain}"
: "${IRCD_ADMIN_LOCATION:=Somewhere}"
: "${IRCD_ADMIN_CONTACT:=root@localhost}"
: "${IRCD_GENERAL_NUMERIC:=1}"

# Marker stamped as the first line of every base.conf THIS script generates.
# Regeneration policy:
#   - no base.conf                 -> generate (and stamp the marker)
#   - base.conf WITH the marker    -> regenerate: env + template are the
#                                     source of truth
#   - base.conf WITHOUT the marker -> user-managed (e.g. volume-mounted,
#                                     hand-edited) -> never touched.
#                                     Previously an unconditional cp
#                                     clobbered such files on every start.
GENMARKER='# GENERATED BY dockerentrypoint.sh from base.conf-dist. Do not hand-edit: this file is REGENERATED ON EVERY CONTAINER START while this marker is the first line. To manage base.conf yourself, replace it with a file that lacks this marker.'

# How a value reaches base.conf.  Every %VARIABLE% placeholder in the
# template is one of two kinds:
#
#   string  the placeholder sits INSIDE a double-quoted conf string, e.g.
#               name = "%IRCD_GENERAL_NAME%";
#           The variable holds the plain value.  The ircd's conf lexer
#           (ircd/ircd_lexer.l, QSTRING) takes every character up to the
#           next '"' as it stands.  It has no escape character: a '\' is an
#           ordinary character and needs nothing done to it, and a '"'
#           cannot be written inside a string at all.  So a value that
#           contains '"' is refused, and any other value is the string the
#           ircd ends up with, byte for byte.
#
#   number  the placeholder stands bare where the conf takes a number, e.g.
#               numeric = %IRCD_GENERAL_NUMERIC%;
#           The value must be decimal digits and nothing else: that is all
#           the lexer takes as a number, and anything more would be read as
#           conf syntax.
#
# The variables named in CONF_NUMBER_VARS are numbers; all others are strings.
CONF_NUMBER_VARS=" IRCD_GENERAL_NUMERIC "

# die MESSAGE: report a fatal error and stop, before the ircd is started.
die() {
    printf 'dockerentrypoint: ERROR: %s\n' "$*" >&2
    [ -n "$GENTMP" ] && rm -f "$GENTMP"
    exit 1
}

# render_template: write the template to stdout with every %NAME%
# replaced by CONF_VALUE[NAME].  The template is read once and substituted
# text is never looked at again, so a value may contain anything -- '&',
# '|', '\', even text that looks like a placeholder -- without being
# reinterpreted.  A placeholder with no CONF_VALUE entry is left as it is
# and its name is added to UNRESOLVED, so the caller can refuse the result.
render_template() {
    local LC_ALL=C re='%([A-Za-z_][A-Za-z0-9_]*)%' line rest name
    UNRESOLVED=
    while IFS= read -r line || [ -n "$line" ]; do
        rest=$line
        line=
        while [[ $rest =~ $re ]]; do
            name=${BASH_REMATCH[1]}
            line+=${rest%%"%$name%"*}
            rest=${rest#*"%$name%"}
            if [ -n "${CONF_VALUE[$name]+x}" ]; then
                line+=${CONF_VALUE[$name]}
            else
                line+="%$name%"
                case " $UNRESOLVED " in
                    *" $name "*) ;;
                    *) UNRESOLVED="${UNRESOLVED:+$UNRESOLVED }$name" ;;
                esac
            fi
        done
        printf '%s\n' "$line$rest" || return 1
    done < "$BASECONFDIST"
}

if [ -f "$BASECONF" ] && ! head -n 1 "$BASECONF" | grep -qF 'GENERATED BY dockerentrypoint.sh'; then
    echo "Found user-managed config at $BASECONF (no generation marker), leaving it alone"
else
    # Check the value of every placeholder the template uses against the
    # conf syntax (see CONF_NUMBER_VARS) before anything is written.  A value
    # with a line break is refused: a conf string cannot span lines (the
    # ircd reads a CR as a line end too), so it could only produce a file
    # the ircd rejects or misreads.
    declare -A CONF_VALUE=()
    errors=
    seen=
    placeholders=$(grep -oE '%[A-Za-z_][A-Za-z0-9_]*%' "$BASECONFDIST")
    while read -r placeholder; do
        [ -n "$placeholder" ] || continue
        # Extract variable name (remove the % signs)
        varname="${placeholder:1:-1}"
        case " $seen " in *" $varname "*) continue ;; esac
        seen+=" $varname"

        # Get the value from environment (indirect expansion)
        value="${!varname}"

        # A variable without a value gets no entry: render_template reports it.
        [ -n "$value" ] || continue

        case "$value" in
            *$'\n'*|*$'\r'*)
                errors+="  $varname contains a line break"$'\n'
                continue ;;
        esac
        case "$CONF_NUMBER_VARS" in
            *" $varname "*)
                case "$value" in
                    *[!0123456789]*)
                        errors+="  $varname must be a number (digits only), not '$value'"$'\n'
                        continue ;;
                esac ;;
            *)
                case "$value" in
                    *'"'*)
                        errors+="  $varname contains a double quote (\"), which a base.conf string cannot hold"$'\n'
                        continue ;;
                esac ;;
        esac
        # The server numeric must also be in range.  The ircd refuses 0; a
        # numeric above 4095 passes its conf check and then aborts the ircd
        # (or, built without assertions, is written past the end of the
        # server table) when the numeric is assigned (numnicks.c,
        # SetYXXServerName).
        if [ "$varname" = IRCD_GENERAL_NUMERIC ]; then
            digits=${value#"${value%%[!0]*}"}
            if [ -z "$digits" ] || [ "${#digits}" -gt 4 ] || [ "$digits" -gt 4095 ]; then
                errors+="  $varname must be a number from 1 to 4095, not '$value'"$'\n'
                continue
            fi
        fi
        CONF_VALUE[$varname]=$value
    done <<< "$placeholders"
    [ -z "$errors" ] || die "refusing to generate $BASECONF:"$'\n'"${errors%$'\n'}"

    # Substitute into a temp file, then stamp the marker and move into
    # place, so a crash mid-generation never leaves a half-substituted
    # marker-less (= treated as user-managed) conf behind.
    GENTMP="$BASECONF.gen.$$"
    render_template > "$GENTMP"

    # Never start the ircd on a conf that still holds a placeholder: the
    # ircd would take the literal %VARIABLE% text as the value (as its
    # server name, for one).
    [ -z "$UNRESOLVED" ] || die "refusing to generate $BASECONF: no value for ${UNRESOLVED// /, }"

    { printf '%s\n' "$GENMARKER"; cat "$GENTMP"; } > "$BASECONF"
    rm -f "$GENTMP"
    GENTMP=

    echo "Generated $BASECONF from template"
fi

#If cmd is the ircd...
if [ "$1" == "/home/nefarious/bin/ircd" ]; then
    # Generate a pem file if there isnt one...
    if [ ! -f /home/nefarious/ircd/ircd.pem ]; then
        echo "Generating self signed ssl key for ircd.pem"
        openssl req -new --x509 -days 365 -nodes -out ircd.pem -newkey rsa:4096 -keyout ircd.pem -subj "/CN=$IRCD_GENERAL_NAME/"
        test 1 -eq 1 || test ! -f /dev/urandom || openssl gendh -rand $1/ircd.rand 512 >> $1/ircd.pem
        test 1 -eq 1 || test -f /dev/urandom || openssl gendh 512 >> $1/ircd.pem
        openssl x509 -subject -dates -fingerprint -noout -in $IRCDPEM

    fi
fi

# Run CMD from Dockerfile
# Optionally wrap with valgrind if NEFARIOUS_VALGRIND=1
if [ "${NEFARIOUS_VALGRIND:-0}" = "1" ]; then
    echo "Running with Valgrind (NEFARIOUS_VALGRIND=1)"
    exec valgrind --leak-check=full --show-leak-kinds=all --track-origins=yes \
        --log-file=/home/nefarious/ircd/cores/valgrind.log "$@"
else
    exec "$@"
fi

